import { ConfigService } from '@nestjs/config';
import { createHash, randomUUID } from 'node:crypto';
import { mkdtemp, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import sharp from 'sharp';
import { MongoClient } from 'mongodb';
import { IamDb } from './iam-db.service';
import { ImageAccess } from './image-access.service';
import { ImageStorage } from './image-storage.service';
import { IamAuth } from './iam-auth.service';

const suite = process.env.NB_MONGO_TEST === '1' ? describe : describe.skip;
suite('real local MongoDB and file storage', () => {
  let db: IamDb,
    storage: ImageStorage,
    access: ImageAccess,
    root: string,
    source: string,
    config: ConfigService;
  const name = 'nanobanana_test_' + randomUUID().replaceAll('-', '');
  const ctx: any = {
    tenant: 1,
    user: 3,
    permissions: ['image:task:list', 'image:asset:view'],
  };
  const iam: any = {
    require: jest.fn().mockResolvedValue({ allowed: true }),
    register: jest.fn().mockResolvedValue({}),
    batch: jest.fn(async (_ctx, _kind, ids) => ids.map(() => true)),
  };
  beforeAll(async () => {
    root = await mkdtemp(join(tmpdir(), 'nb-storage-'));
    config = new ConfigService({
      NB_MONGO_URI: 'mongodb://127.0.0.1:27017',
      NB_MONGO_DB: name,
      NB_IMAGE_ROOT: root,
      IAM_SESSION_KEY: Buffer.alloc(32, 7).toString('base64'),
    });
    db = new IamDb(config);
    await db.onModuleInit();
    storage = new ImageStorage(config);
    access = new ImageAccess(db, iam, storage);
    source =
      'data:image/png;base64,' +
      (
        await sharp({
          create: { width: 2, height: 2, channels: 3, background: '#336699' },
        })
          .png()
          .toBuffer()
      ).toString('base64');
  });
  afterAll(async () => {
    await db?.onModuleDestroy();
    const client = new MongoClient('mongodb://127.0.0.1:27017', {
      serverSelectionTimeoutMS: 3000,
    });
    try {
      await client.connect();
      await client.db(name).dropDatabase();
    } finally {
      await client.close();
    }
    if (root) await rm(root, { recursive: true, force: true });
  });
  beforeEach(() => {
    jest.clearAllMocks();
  });
  it('persists generated bytes, metadata and protected history, without source/base64', async () => {
    const id = await access.begin(ctx, 'ark', {
      prompt: 'blue',
      model: 'test',
    });
    const result = await access.finish(ctx, id, undefined, {
      data: [{ b64_json: source.split(',')[1] }],
    });
    expect(result.data[0].url).toMatch(/^\/api\/workbench\/assets\//);
    const row: any = await db
      .collection('image_assets')
      .findOne({ task_id: id });
    expect(row).toMatchObject({
      status: 'ACTIVE',
      storageProvider: 'local',
      mimeType: 'image/png',
      width: 2,
      height: 2,
    });
    expect(row.source_cipher).toBeUndefined();
    expect(JSON.stringify(row)).not.toContain('base64');
    expect((await access.bytes(ctx, row.id, 'download')).bytes).toEqual(
      Buffer.from(source.split(',')[1], 'base64'),
    );
    const list = await access.list(ctx, 'assets', {
      search: 'blue',
      pageSize: 1,
    });
    expect(list.total).toBe(1);
    expect(list.items[0].url).toBe(result.data[0].url);
    const prepared = await access.prepareInput(ctx, {
      image: result.data[0].url,
    });
    expect(prepared.image).toBe(source);
    expect(
      await access.prepareInput(ctx, { imageUrl: result.data[0].url }),
    ).toEqual({ imageBase64: source });
    expect(
      await access.prepareInput(ctx, { imageUrls: [result.data[0].url] }),
    ).toEqual({ imageBase64List: [source] });
    const second = new IamDb(config);
    await second.onModuleInit();
    try {
      expect(
        await second.collection('image_assets').findOne({ id: row.id }),
      ).not.toBeNull();
    } finally {
      await second.onModuleDestroy();
    }
  });
  it('deduplicates concurrent callbacks and never resurrects deleted assets', async () => {
    const id = await access.begin(ctx, 'ark', {});
    const urls = await Promise.all(
      Array.from({ length: 5 }, () => access.storeAsset(ctx, id, source)),
    );
    expect(new Set(urls).size).toBe(1);
    expect(
      await db.collection('image_assets').countDocuments({ task_id: id }),
    ).toBe(1);
    const row: any = await db
      .collection('image_assets')
      .findOne({ task_id: id });
    await access.remove(ctx, row.id);
    await expect(access.storeAsset(ctx, id, source)).rejects.toThrow();
    await expect(access.bytes(ctx, row.id, 'view')).rejects.toThrow();
  });
  it('does not publish files when image decoding or disk writes fail, and permits retry', async () => {
    const id = await access.begin(ctx, 'ark', {});
    await expect(
      access.storeAsset(ctx, id, 'data:image/png;base64,AAAA'),
    ).rejects.toThrow('INVALID_IMAGE_BYTES');
    expect(
      await db
        .collection('image_assets')
        .countDocuments({ task_id: id, status: 'ACTIVE' }),
    ).toBe(0);
    const spy = jest
      .spyOn(storage, 'save')
      .mockRejectedValueOnce(new Error('disk full'));
    await expect(access.storeAsset(ctx, id, source)).rejects.toThrow(
      'disk full',
    );
    spy.mockRestore();
    await expect(access.storeAsset(ctx, id, source)).resolves.toMatch(
      /preview$/,
    );
  });
  it('keeps pending IAM registration invisible and retries it', async () => {
    const id = await access.begin(ctx, 'ark', {});
    iam.register.mockRejectedValueOnce(new Error('IAM offline'));
    await expect(access.storeAsset(ctx, id, source)).rejects.toThrow(
      'IAM offline',
    );
    const row: any = await db
      .collection('image_assets')
      .findOne({ task_id: id });
    expect(row.status).toBe('REGISTERING');
    await expect(access.bytes(ctx, row.id, 'view')).rejects.toThrow();
    await expect(access.storeAsset(ctx, id, source)).resolves.toMatch(
      /preview$/,
    );
  });
  it('enforces tenant scope and IAM decisions before file access', async () => {
    const id = await access.begin(ctx, 'ark', {});
    await access.storeAsset(ctx, id, source);
    const row: any = await db
      .collection('image_assets')
      .findOne({ task_id: id });
    await expect(
      access.bytes({ ...ctx, tenant: 9 }, row.id, 'view'),
    ).rejects.toThrow('ASSET_NOT_FOUND');
    const spy = jest.spyOn(storage, 'read');
    iam.require.mockRejectedValueOnce(new Error('denied'));
    await expect(access.bytes(ctx, row.id, 'download')).rejects.toThrow(
      'denied',
    );
    expect(spy).not.toHaveBeenCalled();
    spy.mockRestore();
  });
  it('detects file corruption and rejects path traversal', async () => {
    const item = await storage.save(1, 'task', 'asset', source);
    await writeFile(join(root, item.storageKey), 'corrupted');
    await expect(storage.read(item)).rejects.toThrow('IMAGE_FILE_UNAVAILABLE');
    await expect(
      storage.read({ ...item, storageKey: '../outside' }),
    ).rejects.toThrow();
    await expect(storage.save(1, '../task', 'asset', source)).rejects.toThrow(
      'INVALID_STORAGE_ID',
    );
  });
  it('expires sessions before asynchronous TTL cleanup and removes logout sessions', async () => {
    const auth = new IamAuth(config, db, {
      invoke: jest.fn(async (path) =>
        path === '/me' ? { tenantId: 1, userId: 3 } : [],
      ),
    } as any);
    jest.spyOn(auth, 'verifyAccess').mockResolvedValue({ sub: 'user' });
    const id_hash = createHash('sha256').update('session').digest('hex');
    await db
      .collection('iam_sessions')
      .insertOne({
        id_hash,
        token_cipher: auth.seal('token'),
        csrf_token: 'csrf',
        expires_at: new Date(Date.now() - 1),
      });
    const req: any = {
      headers: {
        cookie: 'nb_iam_session=session',
        origin: auth.origin,
        'x-csrf-token': 'csrf',
      },
    };
    await expect(auth.context(req)).rejects.toThrow('SESSION_EXPIRED');
    await db
      .collection('iam_sessions')
      .updateOne(
        { id_hash },
        { $set: { expires_at: new Date(Date.now() + 60000) } },
      );
    await expect(auth.context(req, true)).resolves.toMatchObject({
      tenant: 1,
      user: 3,
    });
    await expect(
      auth.context(
        { headers: { ...req.headers, 'x-csrf-token': 'wrong' } },
        true,
      ),
    ).rejects.toThrow('CSRF_REJECTED');
    await auth.logout(req, { clearCookie: jest.fn() } as any);
    await expect(auth.context(req)).rejects.toThrow('SESSION_EXPIRED');
  });
  it('consumes login states atomically and creates TTL indexes', async () => {
    await db
      .collection('iam_login_states')
      .insertOne({
        state_hash: 'state',
        expires_at: new Date(Date.now() + 60000),
      });
    const results = await Promise.all(
      [1, 2].map(() =>
        db
          .collection('iam_login_states')
          .findOneAndDelete({
            state_hash: 'state',
            expires_at: { $gt: new Date() },
          }),
      ),
    );
    expect(results.filter(Boolean)).toHaveLength(1);
    const indexes = await db.collection('iam_sessions').indexes();
    expect(
      indexes.some((i) => i.expireAfterSeconds === 0 && i.key.expires_at === 1),
    ).toBe(true);
  });
});
